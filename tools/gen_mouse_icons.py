#!/usr/bin/env python3
"""Turn the mouse button icons (loader/res/mouse/*.png, 8-bit RGBA) into loader/src/fe/mouse_icons.inc.

The icons are by fez (shared on the project's Discord). Each one is cropped to the box that holds all of them (so the
mouse is the same size in every icon), padded to a square, scaled down to 64x64 with area averaging and stored as
grey + alpha (the icons are black and white). fe/fonts.cpp scales them again to the size of the fonts' pad buttons.
Standard library only: python tools/gen_mouse_icons.py
"""
import os
import struct
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'loader', 'res', 'mouse')
OUT = os.path.join(ROOT, 'loader', 'src', 'fe', 'mouse_icons.inc')
NAMES = ['left', 'right', 'middle', 'wheel_up', 'wheel_down']  # the order of fonts.cpp's kMouseIcon* codes
SIZE = 64


def png_read(path):
    d = open(path, 'rb').read()
    assert d[:8] == b'\x89PNG\r\n\x1a\n', path
    o, idat, w, h = 8, b'', 0, 0
    while o < len(d):
        n, t = struct.unpack_from('>I4s', d, o)
        body = d[o + 8:o + 8 + n]
        o += 12 + n
        if t == b'IHDR':
            w, h, depth, ctype, _, _, inter = struct.unpack('>IIBBBBB', body)
            assert depth == 8 and ctype == 6 and inter == 0, (path, depth, ctype, inter)
        elif t == b'IDAT':
            idat += body
    raw, stride, bpp = zlib.decompress(idat), w * 4, 4
    out, prev, p = bytearray(), bytearray(stride), 0
    for _ in range(h):
        f, line = raw[p], bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line
        prev = line
    return w, h, out


def main():
    icons = [png_read(os.path.join(SRC, n + '.png')) for n in NAMES]
    x0 = y0 = 1 << 30
    x1 = y1 = -1
    for w, h, px in icons:
        for y in range(h):
            for x in range(w):
                if px[(y * w + x) * 4 + 3] > 8:
                    x0, y0, x1, y1 = min(x0, x), min(y0, y), max(x1, x), max(y1, y)
    side = max(x1 - x0, y1 - y0) + 1
    cx, cy = (x0 + x1 + 1) / 2, (y0 + y1 + 1) / 2
    left, top = cx - side / 2, cy - side / 2
    lines = ['// Generated by tools/gen_mouse_icons.py from loader/res/mouse/*.png (icons by fez). Do not edit.',
             '// %d icons, %dx%d, grey and alpha per pixel: %s' % (len(NAMES), SIZE, SIZE, ', '.join(NAMES)),
             'constexpr int kMouseIconCount = %d, kMouseIconSize = %d;' % (len(NAMES), SIZE),
             'static const unsigned char kMouseIconPixels[%d][%d] = {' % (len(NAMES), SIZE * SIZE * 2)]
    step = side / SIZE
    for (w, h, px), name in zip(icons, NAMES):
        vals = []
        for oy in range(SIZE):
            for ox in range(SIZE):
                sa = sg = n = 0
                for y in range(int(top + oy * step), int(top + (oy + 1) * step)):
                    for x in range(int(left + ox * step), int(left + (ox + 1) * step)):
                        n += 1
                        if 0 <= x < w and 0 <= y < h:
                            q = (y * w + x) * 4
                            a = px[q + 3]
                            sa += a
                            sg += a * (px[q] * 299 + px[q + 1] * 587 + px[q + 2] * 114) // 1000
                vals += [sg // sa if sa else 0, (sa + n // 2) // n if n else 0]
        lines.append('    { // %s' % name)
        for i in range(0, len(vals), 32):
            lines.append('        ' + ','.join(str(v) for v in vals[i:i + 32]) + ',')
        lines.append('    },')
    lines.append('};')
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('crop %d,%d %dx%d -> %s' % (left, top, side, side, OUT))


if __name__ == '__main__':
    main()

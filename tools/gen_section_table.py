#!/usr/bin/env python3
"""Generate a hook table (address, size, name) of every function in one XBE section, for the loader.

Input is notes/functions.csv (from the Ghidra analysis). Output holds addresses and symbol names only,
no game code; it is valid for the one build the loader checks for (SHA-256 in main.cpp).
Usage: python tools/gen_section_table.py D3D loader/src/d3d_functions.inc
       python tools/gen_section_table.py DSOUND loader/src/dsound_functions.inc
"""
import csv
import os
import sys

if len(sys.argv) != 3:
    sys.exit(__doc__)
section, dst = sys.argv[1], sys.argv[2]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "notes", "functions.csv")
rows = [r for r in csv.DictReader(open(src)) if r["section"] == section]
rows.sort(key=lambda r: int(r["address"], 16))
with open(dst, "w", newline="\n") as f:
    f.write("// Generated by tools/gen_section_table.py %s from notes/functions.csv. Do not edit.\n" % section)
    f.write("// Functions in the XBE's %s section (build SHA-256 df2739c3...): address, size in bytes, name.\n" % section)
    for r in rows:
        f.write('{0x%08xu, %su, "%s"},\n' % (int(r["address"], 16), r["size"], r["name"]))
print("wrote %d entries to %s" % (len(rows), dst))

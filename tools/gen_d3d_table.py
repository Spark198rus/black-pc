#!/usr/bin/env python3
"""Generate loader/src/d3d_functions.inc (address, size, name of every function in the XBE's D3D section).

Input is notes/functions.csv (exported from the Ghidra analysis). The table holds addresses and symbol
names only, no game code. It is valid for the one build the loader checks for (SHA-256 in main.cpp).
Usage: python tools/gen_d3d_table.py [notes/functions.csv] [loader/src/d3d_functions.inc]
"""
import csv
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "notes", "functions.csv")
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "loader", "src", "d3d_functions.inc")

rows = [r for r in csv.DictReader(open(src)) if r["section"] == "D3D"]
rows.sort(key=lambda r: int(r["address"], 16))
with open(dst, "w", newline="\n") as f:
    f.write("// Generated by tools/gen_d3d_table.py from notes/functions.csv. Do not edit.\n")
    f.write("// Functions in the XBE's D3D section (build SHA-256 df2739c3...): address, size in bytes, name.\n")
    for r in rows:
        f.write('{0x%08xu, %su, "%s"},\n' % (int(r["address"], 16), r["size"], r["name"]))
print("wrote %d entries to %s" % (len(rows), dst))
